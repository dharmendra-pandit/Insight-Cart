# report.py
"""
Export helpers: turn an analysis result into downloadable
Markdown and JSON reports.
"""

import re
import json

import config
import local_shops
from prices import format_price


def slugify(text: str) -> str:
    """File-name friendly version of a product name."""
    slug = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    return slug or "product"


def to_json(result: dict) -> str:
    return json.dumps(result, indent=2, ensure_ascii=False)


def to_markdown(result: dict) -> str:
    a = result["analysis"]
    scraped = result["scraped"]
    related = (result.get("related") or {}).get("related_products", [])

    score = a.get("sentiment_score")
    rating = a.get("average_user_rating")
    rating_note = {
        "scraped": "published on review pages",
        "ai_estimate": "estimated from review text",
    }.get(a.get("rating_source"), "")
    counts = a.get("sentiment_counts") or {}
    engine = config.ENGINES.get(result.get("engine"), {}).get("label")

    lines = [
        f"# {a['product_name']}: Review Analysis",
        "",
        f"Generated by {config.APP_NAME}{f' ({engine})' if engine else ''} on {result['created_at']}.",
        "",
        "## Overview",
        "",
        f"- Overall sentiment: {a['overall_sentiment']}",
        f"- Sentiment score: {round(score * 100)} / 100" if score is not None else "- Sentiment score: N/A",
        f"- User rating: {rating} / 5 ({rating_note})" if rating is not None else "- User rating: N/A",
        f"- Reviews analyzed: {a['total_reviews_analyzed']}",
    ]
    if counts:
        lines.append(
            f"- Breakdown: {counts.get('Positive', 0)} positive, "
            f"{counts.get('Mixed', 0)} mixed, {counts.get('Negative', 0)} negative"
        )
    lines += [
        f"- Confidence: {a['confidence']}",
        f"- Value for money: {a.get('value_for_money', 'Unknown')}",
        "",
        "## Buying verdict",
        "",
        a["buying_verdict"],
        "",
    ]
    if a.get("summary"):
        lines += ["## Summary", "", a["summary"], ""]

    price_data = result.get("prices") or {}
    lines += ["## Where to buy", ""]
    if a.get("value_reason"):
        lines += [f"Value for money: {a.get('value_for_money', 'Unknown')}. {a['value_reason']}", ""]
    if price_data.get("offers"):
        stock = {True: "in stock", False: "out of stock", None: "stock unknown"}
        for o in price_data["offers"]:
            mrp = f", MRP {format_price(o['mrp'], o['currency'])}" if o.get("mrp") else ""
            lines.append(
                f"- {format_price(o['price'], o['currency'])} at {o['store']} "
                f"({stock[o['in_stock']]}{mrp}): {o['url']}"
            )
    else:
        lines.append("- No store prices could be read for this product.")
    lines.append("")

    local = result.get("local_shops")
    if local:
        lines += [f"## Shops near {local['location']}", ""]
        for s in local["shops"]:
            phone = f", phone {s['phone']}" if s["phone"] else ""
            link = s["maps_url"] or s["website"] or s["source"]
            lines.append(
                f"- **{s['name']}** ({', '.join(local_shops.checks(s))}): {s['address']}{phone}. {link}"
            )
        if not local["shops"]:
            lines.append(f"- {local['error'] or 'No verified shops were found.'}")
        lines.append("")

    lines += ["## Pros", ""] + _points(a["pros"], a.get("pro_mentions")) + [""]
    lines += ["## Cons", ""] + _points(a["cons"], a.get("con_mentions")) + [""]

    if related:
        lines += ["## Alternatives (suggested)", ""]
        for p in related:
            notes = []
            if p["ai_suggested_rating"]:
                notes.append(f"rating about {p['ai_suggested_rating']} / 5")
            if p.get("approx_price"):
                notes.append(f"price about {format_price(p['approx_price'], p.get('currency', config.PRICE_CURRENCY))}")
            extra = f" (estimates: {', '.join(notes)})" if notes else ""
            lines.append(f"- **{p['name']}**{extra}: {p['why_similar']}")
        lines.append("")

    lines += ["## Sources", ""]
    if scraped["sources"]:
        lines += [f"- {url}" for url in scraped["sources"]]
    else:
        lines.append("- Reviews pasted manually")

    lines += [
        "",
        "---",
        "AI-generated summary of public reviews. Alternatives and their ratings and "
        "prices are estimates; always verify on the store before buying.",
        "",
    ]
    return "\n".join(lines)


def _points(texts: list[str], mentions: list[int] | None) -> list[str]:
    """Bullet lines for pros or cons, with how many reviews mention each."""
    if not texts:
        return ["- None identified"]
    mentions = mentions or [0] * len(texts)
    return [
        f"- {text} ({n} {'review' if n == 1 else 'reviews'})" if n else f"- {text}"
        for text, n in zip(texts, mentions)
    ]
